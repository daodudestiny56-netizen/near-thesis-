"""Stage 6 - report: write RESULTS.md from results.json and validation.json (no hand-typed numbers)."""
from __future__ import annotations

import json

from . import config as C


def pct(x, d=1):
    return "n/a" if x is None else f"{x * 100:.{d}f}%"


def ci(r, k, d=1):
    return f"{pct(r.get(k), d)} ({pct(r.get(k + '_lo'), d)}–{pct(r.get(k + '_hi'), d)})" if r.get(k) is not None else "n/a"


def run() -> None:
    res = json.loads((C.DERIVED / "results.json").read_text())
    vpath = C.DERIVED / "validation.json"
    val = json.loads(vpath.read_text()) if vpath.exists() else {}
    M = res["monthly"]
    g = res["generated_from"]
    L = []
    w = L.append
    w("# Results\n")
    w("_Generated by `python -m census report`; do not edit by hand. Method and limits: [METHODOLOGY.md](METHODOLOGY.md)._\n")
    w(f"**Sample:** {g['months']} months ({g['first']} → {g['last']}), {g['blocks']:,} random blocks, {g['txs']:,} transactions. "
      "Intervals are 95% cluster-bootstrap over blocks.\n")

    w("## Latest months\n")
    w("| Month | Automated share of txs | 3-month pooled | Upper bound | Fees initiated by automated | Fees paid by automated | Relayed | To `intents.near` |")
    w("|---|---|---|---|---|---|---|---|")
    for r in M[-6:]:
        w(f"| {r['period']} | {ci(r, 'tx_auto')} | {ci(r, 'tx_auto_r3')} | {pct(r.get('tx_auto_upper'))} | "
          f"{ci(r, 'fee_init_auto')} | {pct(r.get('fee_paid_auto'))} | {pct(r.get('relayed'))} | {pct(r.get('to_intents'), 2)} |")

    w("\n## Robustness of the headline share\n")
    w("| Month | Threshold 40 | Threshold 50 (used) | Threshold 60 | Bias-adjusted (Rogan–Gladen) |")
    w("|---|---|---|---|---|")
    for r in M[-6:]:
        adj = ci(r, "tx_auto_adj") if r.get("tx_auto_adj") is not None else "n/a"
        w(f"| {r['period']} | {pct(r.get('tx_auto_t40'))} | {pct(r.get('tx_auto'))} | {pct(r.get('tx_auto_t60'))} | {adj} |")
    w("\nThe bias adjustment uses the error rates measured on the validation test split and ignores their own "
      "uncertainty; those rates are optimistic (see validation limits), so treat the adjusted figure as a sensitivity, not a correction to trust.\n")

    if val:
        t, d = val.get("test", {}), val.get("dev", {})
        w("## Validation\n")
        w(f"Labelled accounts matched in the sample: {val.get('n_matched')} of {val.get('n_labels')}. "
          f"Label sources: {', '.join(f'{k}: {v}' for k, v in (val.get('label_sources') or {}).items())}.\n")
        w("| Split | Labelled | Classified (coverage) | Recall automated | Recall human | Precision automated | Balanced accuracy |")
        w("|---|---|---|---|---|---|---|")
        for name, s in (("**Test (held out)**", t), ("Dev (rules were tuned here)", d)):
            if not s:
                continue
            w(f"| {name} | {s['n_labelled']} | {s['n_classified']} ({pct(s['coverage'], 0)}) | "
              f"{pct(s['recall_automated'], 0)} [{pct(s['recall_automated_ci'][0], 0)}–{pct(s['recall_automated_ci'][1], 0)}] | "
              f"{pct(s['recall_human'], 0)} [{pct(s['recall_human_ci'][0], 0)}–{pct(s['recall_human_ci'][1], 0)}] | "
              f"{pct(s['precision_automated'], 0)} | {pct(s['balanced_accuracy'], 0)} |")
        if t.get("auc") is not None:
            w(f"\nROC AUC of the raw score on the test split: **{t['auc']:.2f}**. Wilson 95% intervals in brackets.\n")
        w("### Leave-one-rule-out ablation (test balanced accuracy)\n")
        ab = val.get("ablation_test_balanced_accuracy", {})
        base = ab.get("all_rules")
        w("| Rule removed | Balanced accuracy | Change |")
        w("|---|---|---|")
        w(f"| _(none)_ | {pct(base)} | |")
        for k, v in sorted(((k, v) for k, v in ab.items() if k.startswith("without:")), key=lambda kv: (kv[1] if kv[1] is not None else 9)):
            w(f"| {k[8:]} | {pct(v)} | {'n/a' if v is None or base is None else f'{(v - base) * 100:+.1f} pts'} |")
        w("\n### Threshold sweep (test)\n")
        w("| Threshold | Balanced accuracy | Recall automated | Recall human |")
        w("|---|---|---|---|")
        for s in val.get("threshold_sweep_test", []):
            w(f"| {s['threshold']} | {pct(s['balanced_accuracy'], 0)} | {pct(s['recall_automated'], 0)} | {pct(s['recall_human'], 0)} |")

    f = res.get("forecast") or {}
    if f:
        w("\n## Trend extrapolation (not a prediction)\n")
        w(f"Logit-linear fit over {f['fit_months'][0]} → {f['fit_months'][-1]}; slope positive in {pct(f['prob_slope_positive'], 0)} "
          "of bootstrap replicates. The band is sampling noise only.\n")
        w("| Month | Median | 95% band |")
        w("|---|---|---|")
        for m, a, lo, hi in zip(f["horizon"], f["share_p50"], f["share_lo"], f["share_hi"]):
            w(f"| {m} | {pct(a)} | {pct(lo)}–{pct(hi)} |")

    c = res.get("concentration") or {}
    if c:
        w(f"\n## Concentration\n\n{c['accounts_for_half_of_automated_txs']} of {c['automated_accounts_in_sample']} automated accounts "
          f"account for half of automated transactions sampled in {c['periods'][0]}–{c['periods'][-1]}.\n")
        w("| Account | Share of all txs | Share of all fees | Main receiver | Relayed |")
        w("|---|---|---|---|---|")
        for a in c["top_automated"]:
            w(f"| `{a['account']}` | {pct(a['tx_share'])} | {pct(a['fee_share'])} | `{a['top_receiver']}` | {pct(a['relayed'], 0)} |")

    w("\n## Every month\n")
    w("| Month | Blocks | Txs sampled | Automated | Human-like | Low-activity | Fees initiated | Fees paid |")
    w("|---|---|---|---|---|---|---|---|")
    for r in M:
        w(f"| {r['period']} | {r['blocks']} | {r['txs_sampled']} | {ci(r, 'tx_auto', 0)} | {pct(r.get('tx_human'), 0)} | "
          f"{pct(r.get('tx_low'), 0)} | {pct(r.get('fee_init_auto'), 0)} | {pct(r.get('fee_paid_auto'), 0)} |")
    (C.ROOT / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote RESULTS.md")


if __name__ == "__main__":
    run()
