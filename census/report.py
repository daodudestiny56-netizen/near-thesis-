"""Stage 6 - report: write RESULTS.md from results.json and validation.json (no hand-typed numbers)."""
from __future__ import annotations

import json

from . import config as C


def pct(x, d=1):
    return "n/a" if x is None else f"{x * 100:.{d}f}%"


def ci(r, k, d=1):
    return f"{pct(r.get(k), d)} ({pct(r.get(k + '_lo'), d)}–{pct(r.get(k + '_hi'), d)})" if r.get(k) is not None else "n/a"


def run() -> None:
    res = json.loads((C.DERIVED / "results.json").read_text())
    vpath = C.DERIVED / "validation.json"
    val = json.loads(vpath.read_text()) if vpath.exists() else {}
    M = res["monthly"]
    g = res["generated_from"]
    L = []
    w = L.append
    w("# Results\n")
    w("_Generated by `python -m census report`; do not edit by hand. Method and limits: [METHODOLOGY.md](METHODOLOGY.md)._\n")
    w(f"**Sample:** {g['months']} months ({g['first']} → {g['last']}), {g['blocks']:,} random blocks, {g['txs']:,} transactions. "
      "Intervals are 95% cluster-bootstrap over blocks.\n")

    w("## Latest months\n")
    w("| Month | Automated share of txs | 3-month pooled | Upper bound | Fees initiated by automated | Fees paid by automated | Relayed | To `intents.near` |")
    w("|---|---|---|---|---|---|---|---|")
    for r in M[-6:]:
        w(f"| {r['period']} | {ci(r, 'tx_auto')} | {ci(r, 'tx_auto_r3')} | {pct(r.get('tx_auto_upper'))} | "
          f"{ci(r, 'fee_init_auto')} | {pct(r.get('fee_paid_auto'))} | {pct(r.get('relayed'))} | {pct(r.get('to_intents'), 2)} |")

    w("\n## Robustness of the headline share\n")
    w("| Month | Threshold 40 | Threshold 50 (used) | Threshold 60 | Bias-adjusted (Rogan–Gladen) |")
    w("|---|---|---|---|---|")
    for r in M[-6:]:
        adj = ci(r, "tx_auto_adj") if r.get("tx_auto_adj") is not None else "n/a"
        w(f"| {r['period']} | {pct(r.get('tx_auto_t40'))} | {pct(r.get('tx_auto'))} | {pct(r.get('tx_auto_t60'))} | {adj} |")
    w("\nThe bias adjustment uses the error rates measured on the validation test split and ignores their own "
      "uncertainty; those rates are optimistic (see validation limits), so treat the adjusted figure as a sensitivity, not a correction to trust.\n")

    if val:
        t, d = val.get("test", {}), val.get("dev", {})
        w("## Validation\n")
        w(f"Labelled accounts matched in the sample: {val.get('n_matched')} of {val.get('n_labels')}. "
          f"Label sources: {', '.join(f'{k}: {v}' for k, v in (val.get('label_sources') or {}).items())}.\n")
        w("| Split | Labelled | Classified (coverage) | Recall automated | Recall human | Precision automated | Balanced accuracy |")
        w("|---|---|---|---|---|---|---|")
        for name, s in (("**Test (held out)**", t), ("Dev (rules were tuned here)", d)):
            if not s:
                continue
            w(f"| {name} | {s['n_labelled']} | {s['n_classified']} ({pct(s['coverage'], 0)}) | "
              f"{pct(s['recall_automated'], 0)} [{pct(s['recall_automated_ci'][0], 0)}–{pct(s['recall_automated_ci'][1], 0)}] | "
              f"{pct(s['recall_human'], 0)} [{pct(s['recall_human_ci'][0], 0)}–{pct(s['recall_human_ci'][1], 0)}] | "
              f"{pct(s['precision_automated'], 0)} | {pct(s['balanced_accuracy'], 0)} |")
        if t.get("auc") is not None:
            w(f"\nROC AUC of the raw score on the test split: **{t['auc']:.2f}**. Wilson 95% intervals in brackets.\n")
        w("### Leave-one-rule-out ablation (test balanced accuracy)\n")
        ab = val.get("ablation_test_balanced_accuracy", {})
        base = ab.get("all_rules")
        w("| Rule removed | Balanced accuracy | Change |")
        w("|---|---|---|")
        w(f"| _(none)_ | {pct(base)} | |")
        for k, v in sorted(((k, v) for k, v in ab.items() if k.startswith("without:")), key=lambda kv: (kv[1] if kv[1] is not None else 9)):
            w(f"| {k[8:]} | {pct(v)} | {'n/a' if v is None or base is None else f'{(v - base) * 100:+.1f} pts'} |")
        w("\n### Threshold sweep (test)\n")
        w("| Threshold | Balanced accuracy | Recall automated | Recall human |")
        w("|---|---|---|---|")
        for s in val.get("threshold_sweep_test", []):
            w(f"| {s['threshold']} | {pct(s['balanced_accuracy'], 0)} | {pct(s['recall_automated'], 0)} | {pct(s['recall_human'], 0)} |")

    ab = (res.get("windows") or {}).get("abs")
    if ab:
        win = res["windows"]
        w_ = L.append
        w_("\n## Absolute activity per second (first window vs latest window)\n")
        w_(f"{win['a'][0]} to {win['a'][-1]} compared with {win['b'][0]} to {win['b'][-1]}. Block time {ab['_sec_per_block']['a']:.2f} s then, {ab['_sec_per_block']['b']:.2f} s now "
           "(measured from the sampled heights and timestamps). Multiples are latest divided by first, with 95% bootstrap intervals.\n")
        w_("| Quantity | First window | Latest window | Multiple | 95% interval |")
        w_("|---|---|---|---|---|")
        names = {"total_tx_per_block": ("All transactions", "tx/s", 1), "auto_tx_per_block": ("Automated transactions", "tx/s", 1),
                 "human_tx_per_block": ("Human-like transactions", "tx/s", 1), "intents_tx_per_block": ("Addressed to `intents.near`", "tx/s", 2),
                 "total_fee_per_block": ("All fee burn", "NEAR/s", 4), "auto_fee_per_block": ("Fee burn initiated by automated", "NEAR/s", 4)}
        for k, (label, unit, d) in names.items():
            v = ab.get(k)
            if not v:
                continue
            mult = "n/a (first window is about zero)" if v.get("ratio_per_s") is None else f"x{v['ratio_per_s']:.2f}"
            ci_ = "" if v.get("ratio_per_s_lo") is None else f"x{v['ratio_per_s_lo']:.2f} to x{v['ratio_per_s_hi']:.2f}"
            w_(f"| {label} | {v['per_s_a']:.{d}f} {unit} | {v['per_s_b']:.{d}f} {unit} | {mult} | {ci_} |")
        if res.get("bottom_line"):
            w_("\n**Bottom line.** " + res["bottom_line"].replace("**", "") + "\n")

    sup = res.get("supply") or {}
    if sup.get("windows"):
        sw, vw = sup["windows"], (sup.get("value") or {}).get("windows") or {}
        L.append("\n## Supply, burn and value capture\n")
        st = sup.get("issuance_step")
        if st:
            L.append(f"**Net issuance step.** Measured from block-header supply, net issuance fell from {st['before']:.2f} NEAR/s ({st['before_pct_per_year']:.2f}% of supply per year) "
                     f"in {st['from']} to {st['after']:.2f} NEAR/s ({st['after_pct_per_year']:.2f}% per year) in {st['to']} (intervals disjoint). The cause is not determined here.\n")
        L.append("| Window | Net issuance | Estimated burn | Gross issuance | Burn / gross issuance |")
        L.append("|---|---|---|---|---|")
        for tag in ("a", "b"):
            x = sw[tag]
            L.append(f"| {x['periods'][0]} to {x['periods'][-1]} | {x['net_issuance_ps']:.3f} NEAR/s | {x['burn_ps']:.4f} NEAR/s | {x['gross_issuance_ps']:.3f} NEAR/s | "
                     f"{pct(x['burn_cover'], 2)} ({pct(x['burn_cover_ci'][0], 2)}-{pct(x['burn_cover_ci'][1], 2)}) |")
        L.append("\nBurn = block-header fee x 0.70 on protocol <= v86 (contracts received 30% of burnt gas) and x 1.00 from v87, per NEAR's gas docs. Gross issuance = net issuance + burn.\n")
        if vw.get("a") and vw.get("b"):
            L.append("**Intents revenue (third-party: DefiLlama snapshot, used as published) against issuance valued at the average NEAR price:**\n")
            L.append("| Window | NEAR price | Intents revenue/day | Issuance/day | L1 fees/day | Revenue / issuance | Revenue / L1 fees |")
            L.append("|---|---|---|---|---|---|---|")
            for tag in ("a", "b"):
                x = vw[tag]
                L.append(f"| {x['periods'][0]} to {x['periods'][-1]} | ${x['near_price_usd']:.2f} | ${x['intents_revenue_usd_day']:,.0f} | ${x['issuance_usd_day']:,.0f} | "
                         f"${x['l1_fees_usd_day']:,.0f} | {pct(x['revenue_cover'], 1)} | x{x['revenue_vs_l1_fees']:.1f} |")
            L.append(f"\nSnapshot retrieved {(sup['value'] or {}).get('snapshot_retrieved_on')}. Per DefiLlama, Intents revenue is NEAR's net captured revenue and, since 2026-02-23, is used for open-market buybacks, not burned.\n")
    regimes = res.get("regimes") or []
    if regimes:
        L.append("## Breakpoints detected from the data\n")
        L.append("| Kind | Month | Change |")
        L.append("|---|---|---|")
        for g in regimes:
            L.append(f"| {g['kind']} | {g['at']} | {g['label']} |")
        L.append("")

    c = res.get("concentration") or {}
    if c:
        w(f"\n## Concentration\n\n{c['accounts_for_half_of_automated_txs']} of {c['automated_accounts_in_sample']} automated accounts "
          f"account for half of automated transactions sampled in {c['periods'][0]}–{c['periods'][-1]}.\n")
        w("| Account | Share of all txs | Share of all fees | Main receiver | Relayed |")
        w("|---|---|---|---|---|")
        for a in c["top_automated"]:
            w(f"| `{a['account']}` | {pct(a['tx_share'])} | {pct(a['fee_share'])} | `{a['top_receiver']}` | {pct(a['relayed'], 0)} |")

    w("\n## Every month\n")
    w("| Month | Blocks | Txs sampled | Automated | Human-like | Low-activity | Fees initiated | Fees paid |")
    w("|---|---|---|---|---|---|---|---|")
    for r in M:
        w(f"| {r['period']} | {r['blocks']} | {r['txs_sampled']} | {ci(r, 'tx_auto', 0)} | {pct(r.get('tx_human'), 0)} | "
          f"{pct(r.get('tx_low'), 0)} | {pct(r.get('fee_init_auto'), 0)} | {pct(r.get('fee_paid_auto'), 0)} |")
    (C.ROOT / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote RESULTS.md")
    write_readme_block(res, val)


START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def write_readme_block(res: dict, val: dict) -> None:
    """Replace the block between the markers in README.md with a summary computed from the data."""
    readme = C.ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        return
    lw = res["latest_window"]["metrics"]
    span = res["latest_window"]["periods"]
    g = res["generated_from"]
    a, lo, hi, fi, fp = lw["tx_auto"], lw["tx_auto_t60"], lw["tx_auto_t40"], lw["fee_init_auto"], lw["fee_paid_auto"]
    L = [START, "",
         f"**Headline results** (computed from {g['blocks']:,} random blocks and {g['txs']:,} transactions, {g['first']} to {g['last']}; "
         "regenerated by `python -m census reproduce`, full tables in [RESULTS.md](RESULTS.md)):", "",
         f"* **Level.** Over {span[0]} to {span[-1]}, **{pct(a['point'])}** of sampled transactions were initiated by accounts that behave like software "
         f"(95% CI {pct(a['lo'])} to {pct(a['hi'])}; {pct(lo['point'])} to {pct(hi['point'])} across classifier cut-offs)."]
    wm = (res.get("windows") or {}).get("metrics", {})
    w = res.get("windows")
    if wm.get("tx_auto"):
        m = wm["tx_auto"]
        L.append(f"* **Trend.** {w['a'][0]}-{w['a'][-1]} to {w['b'][0]}-{w['b'][-1]}: {pct(m['a'], 1)} to {pct(m['b'], 1)} "
                 f"({m['diff'] * 100:+.1f} pts, 95% CI {m['diff_lo'] * 100:+.1f} to {m['diff_hi'] * 100:+.1f}).")
        nl = wm.get("tx_auto_nolife")
        if nl:
            L.append(f"  Without the lifetime-volume rules (which grow with account age) it is {pct(nl['a'], 1)} to {pct(nl['b'], 1)} "
                     f"({nl['diff'] * 100:+.1f} pts, CI {nl['diff_lo'] * 100:+.1f} to {nl['diff_hi'] * 100:+.1f}): the direction survives, the size shrinks.")
    L.append(f"* **Fees.** Automated accounts initiated {pct(fi['point'])} of fees (CI {pct(fi['lo'])} to {pct(fi['hi'])}) and fee payers classified as "
             f"automated paid {pct(fp['point'])} (CI {pct(fp['lo'])} to {pct(fp['hi'])}); {pct(lw['relayed']['point'])} of transactions were relayed.")
    t = val.get("test") or {}
    if t.get("n_classified"):
        L.append(f"* **Accuracy (held-out test split, n={t['n_classified']}).** Recall for automated {pct(t['recall_automated'])} "
                 f"(Wilson CI {pct(t['recall_automated_ci'][0])} to {pct(t['recall_automated_ci'][1])}), for human {pct(t['recall_human'])}, "
                 f"balanced accuracy {pct(t['balanced_accuracy'])}, ROC AUC {t.get('auc', float('nan')):.2f}. Labels are biased toward self-declared bots, "
                 "so treat this as an optimistic ceiling.")
    ab = (res.get("windows") or {}).get("abs") or {}
    if ab.get("auto_tx_per_block") and ab.get("total_tx_per_block"):
        a_, t_, f_ = ab["auto_tx_per_block"], ab["total_tx_per_block"], ab.get("auto_fee_per_block")
        L.append(f"* **Absolute activity (per second, block-time corrected).** Total activity went {t_['per_s_a']:.1f} to {t_['per_s_b']:.1f} tx/s; "
                 f"automated went {a_['per_s_a']:.1f} to {a_['per_s_b']:.1f} tx/s (x{a_['ratio_per_s']:.2f}, 95% CI x{a_['ratio_per_s_lo']:.2f} to x{a_['ratio_per_s_hi']:.2f})"
                 + (f"; fee burn initiated by automated accounts went {f_['per_s_a']:.4f} to {f_['per_s_b']:.4f} NEAR/s." if f_ else ".")
                 + " **The share rose because other activity fell faster, not because software activity grew.**")
    sup = res.get("supply") or {}
    sw_, vw_ = sup.get("windows"), ((sup.get("value") or {}).get("windows")) or {}
    if sw_ and sup.get("issuance_step"):
        st_ = sup["issuance_step"]
        L.append(f"* **Does usage pay for issuance?** Estimated L1 burn covered {pct(sw_['b']['burn_cover'], 2)} of gross issuance in {sw_['b']['periods'][0]} to {sw_['b']['periods'][-1]}. "
                 + (f"Reported Intents revenue (DefiLlama) covered {pct(vw_['b']['revenue_cover'])}, up from {pct(vw_['a']['revenue_cover'])} (x{vw_['b']['intents_revenue_usd_day'] / vw_['a']['intents_revenue_usd_day']:.1f} revenue, "
                    f"x{vw_['b']['issuance_usd_day'] / vw_['a']['issuance_usd_day']:.2f} issuance in USD). " if vw_.get("a") and vw_.get("b") else "")
                 + f"Net issuance itself fell from {st_['before']:.2f} to {st_['after']:.2f} NEAR/s between {st_['from']} and {st_['to']}.")
    counts = {}
    for c in res.get("claims", []):
        counts[c["verdict"]] = counts.get(c["verdict"], 0) + 1
    names = {"supported": "supported", "not_supported": "not supported", "inconclusive": "inconclusive", "info": "descriptive"}
    L.append("* **Thesis verdicts** (decided by code from the intervals, see [THESIS.md](THESIS.md)): "
             + ", ".join(f"{n} {names[k]}" for k, n in sorted(counts.items())) + ".")
    L += ["", END]
    readme.write_text(text[:text.index(START)] + "\n".join(L) + text[text.index(END) + len(END):], encoding="utf-8")
    print("updated README headline block")


if __name__ == "__main__":
    run()
